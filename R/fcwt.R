#' Fast continuous wavelet transform
#'
#' The core function of this package making use of the fCWT library. It processes
#' an input signal in form of a real valued numeric vector interpreted as an
#' evenly spaced time series and returns the absolute values of the continuous
#' wavelet transform,  i.e. a real valued positive matrix with a time and a
#' frequency dimension. Optionally (`phase = TRUE`), phase information is
#' returned as well, in form of an instantaneous frequency and a phase
#' coherence.
#'
#' @details
#' The wavelet used in this calculation is the so called Morlet wavelet,
#' a sinusoidal wave modulated by a Gaussian whose spread is controlled by
#' the argument `sigma`.
#'
#' See the original paper
#' Arts, L.P.A., van den Broek, E.L.
#' The fast continuous wavelet transformation (fCWT) for real-time, high-quality,
#' noise-resistant time–frequency analysis.
#' Nat Comput Sci 2, 47–58 (2022). \doi{10.1038/s43588-021-00183-z}
#'
#' @param x
#'  Real-valued time series. The time steps are assumed to be evenly spaced.
#'
#' @param x_sample_freq
#'  Sampling rate of input time series `x`. This number primarily establishes
#'  a connection to physical units which is used in other frequency definitions
#'  as well as the units of the output data. Expects either a value with frequency
#'  units, generated with [u()], or a pure number, in which case it is
#'  interpreted in units of 'Hertz'. It does not need to be an integer.
#'
#' @param y_sample_freq
#'  Sampling rate of output time series, in frequency units (see [u()]).
#'  The default value is set so that it aligns with the physical time resolution
#'  of the highest frequency modes.
#'  The maximum allowed sampling rate is the sampling rate of the input signal
#'  `x_sample_freq`.
#'  Since the output is generated by pooling an integer number of input
#'  samples (the modulus is pooled as root mean square,
#'  \eqn{\sqrt{\mathrm{mean} |W|^2}}), the actual output sampling rate is `x_sample_freq / k`, where
#'  `k = floor(x_sample_freq / y_sample_freq)`. It is equal to or slightly
#'  higher than `y_sample_freq` and is stored in the result.
#'
#' @param n_freqs
#'  Number of frequency bins generated by the CWT. The frequencies
#'  are linearly or logarithmically distributed, depending on the `freq_scale`
#'  argument. Computation time increases when raising the
#'  number of frequency bins.
#'  The default number is chosen such that the frequency bandwidths are of the
#'  size of the physical frequency resolutions in case of a logarithmic scale.
#'  In some sense this value constitutes the "physical" limit.
#'  However, increasing `n_freqs` beyond this limit can still make sense: If
#'  we have a signal of a precise frequency, and the probing frequency band is
#'  not exactly aligned, the output signal will be dampened. In this case it
#'  can be useful to increase `n_freqs` and perform appropriate averaging
#'  afterwards: the output signal will show improved response.
#'
#' @param freq_begin,freq_end
#'  Optionally specifies the frequency range `[freq_begin, freq_end]`
#'  (both inclusive). If not
#'  specified the maximal meaningful frequency range, depending on the input signal,
#'  is taken: from `2 * x_sample_freq / length(x)` up to the Nyquist frequency
#'  `x_sample_freq / 2`.
#'  A frequency-valued number, generated with [u()], or a pure number, that is
#'  interpreted in units of 'Hertz'.
#'
#' @param freq_scale
#'  One of `"log"` (default) or `"linear"`: should the `n_freqs` frequencies be
#'  distributed logarithmically or linearly between `freq_begin` and `freq_end`?
#'  The default scale is logarithmic since differences on a logarithmic scale
#'  are proportional to the frequency uncertainties.
#'  In this sense, the logarithmic frequency scale is actually the natural
#'  scale for the continuous wavelet transform.
#'
#' @param sigma
#'  Sets a dimensionless parameter \eqn{\Sigma} controlling the wavelet spread.
#'  Changing this parameter adjusts the time/frequency uncertainty balance,
#'  \eqn{\Delta t = 4 \frac{\Sigma}{f}}, \eqn{\Delta f = 4 \frac{f}{2\pi \Sigma}}.
#'  Larger (lower) value of sigma corresponds to a better (worse) frequency
#'  resolution and a worse (better) time resolution.
#'
#'  For more information, see \code{vignette("sigma", package = "fCWTr")}).
#'
#'  Defaults to \eqn{2\pi}. Note that there is not really a natural choice for
#'  sigma, it depends on the use case. So the default choice can very well be
#'  quite a bad choice (it probably is for audio data).
#'  See [sigma_from_time_res()], [sigma_from_freq_res()] and
#'  [sigma_from_freq_res_rel()] to determine sigma from resolution requirements.
#'
#' @param phase
#'  `FALSE` (default) or `TRUE`. If `TRUE`, phase information is computed in
#'  addition to the modulus, see the "Phase information" section.
#'
#' @param rm_coi
#'  `TRUE` (default) or `FALSE`.
#'  Boundary effects can result in nonphysical artifacts. If `rm_coi = TRUE`,
#'  those are effectively removed by setting corresponding values to `NA`.
#'  We define the essential support of the (Gaussian) wavelet at frequency
#'  \eqn{f} to be four times its standard deviation \eqn{\Sigma / f}, i.e.
#'  \eqn{\Delta t = 4 \frac{\Sigma}{f}}, and so a wavelet touches
#'  the boundary if the distance of the center of the wavelet to the boundary
#'  is less than \eqn{\Delta t / 2}. Values that fall into that range
#'  (the "cone of influence") are removed if `rm_coi = TRUE`.
#'  The phase coherence (see `phase`) is derived from wavelet coefficients
#'  that lie further apart in time, so its cone of influence is wider
#'  (\eqn{3 \frac{\Sigma}{f}} instead of \eqn{2 \frac{\Sigma}{f}}).
#'
#' @param n_threads
#'  Number of threads used by the computation, if supported by your platform.
#'  Defaults to 2 threads (to accommodate CRAN requirements).
#'  If [openmp_enabled()] returns `FALSE`, this argument is ignored, and
#'  only a single thread is used.
#'
#' @section Phase information:
#' With `phase = TRUE`, two quantities are derived from the phase of the
#' (complex) wavelet coefficients \eqn{W(b)} of each frequency band, for each
#' window of input samples that is pooled into one output sample.
#' Both are computed from lag products
#' \eqn{P_\Delta(b) = W(b + \Delta) \overline{W(b)}}, whose phase is the phase
#' advance over \eqn{\Delta} input samples, and which are weighted by the
#' energy \eqn{|W(b)| |W(b + \Delta)|}. A lag product belongs to the window
#' that contains its center \eqn{b + \Delta / 2}.
#'
#' \describe{
#'   \item{Instantaneous frequency}{The (energy weighted) mean frequency of the
#'     window, \eqn{\arg(\sum P_1) / (2 \pi)} times the input sampling rate,
#'     using \eqn{\Delta = 1} sample. (The phase is taken relative to the band's
#'     center frequency \eqn{f}, so the result lies within
#'     \eqn{f \pm x_{sample\_freq} / 2}.)
#'     It can resolve frequencies far more precisely than the frequency
#'     resolution of the wavelet: for a pure tone, all frequency bands that
#'     respond to it report its frequency. In bands with (nearly) no signal it is
#'     of little meaning, so consider it together with the modulus.
#'     This is the "pulse-pair" estimator, see also Kay, S. (1989), A fast and
#'     accurate single frequency estimator, IEEE Transactions on Acoustics,
#'     Speech, and Signal Processing 37 (12), 1987-1990.}
#'   \item{Phase coherence}{How steadily the phase advances within the window:
#'     \eqn{|\sum P_\Delta| / \sum |W(b)| |W(b + \Delta)|}, a number between 0
#'     and 1, using a lag of two standard deviations of the wavelet in time,
#'     \eqn{\Delta = 2 \frac{\Sigma}{f}}. A steady oscillation gives 1.
#'     The lag needs to be that long: over shorter time spans, the (narrow-band)
#'     output of a frequency band looks like a steady oscillation even for noise.
#'     Note that the coherence depends on the window length: for windows that
#'     are short compared to \eqn{\Delta} (typically at low frequencies), it is
#'     close to 1 by construction (all lag products of the window are almost the
#'     same). For white noise, it decreases with the window length towards
#'     \eqn{\frac{4}{\pi} e^{-1} \approx 0.47} (\eqn{e^{-1}} is the correlation
#'     of the wavelet coefficients over the lag), which is reached for windows
#'     of about a hundred \eqn{\frac{\Sigma}{f}}.}
#' }
#'
#' @return
#'  The scalogram, a numeric real-valued matrix with a time (rows) and a
#'  frequency (columns) dimension, curated with some additional properties.
#'  Its dimensions are `c(ceiling(length(x) / k), n_freqs)`, where `k` is the
#'  number of input samples averaged per output sample (see `y_sample_freq`;
#'  `k = 1` if `y_sample_freq = x_sample_freq`). The columns are ordered from
#'  the highest (`freq_end`) to the lowest (`freq_begin`) frequency.
#'
#'  With `phase = TRUE`, the result is a three-dimensional array instead,
#'  with the layers (third dimension) `"modulus"`, `"inst_freq"` (the
#'  instantaneous frequency in Hertz) and `"coherence"`, see the section
#'  "Phase information".
#'
#'  This matrix is wrapped into a S3-class `fcwtr_scalogram` so that plotting and
#'  coercion functions can be used conveniently. Use [as.matrix()] to strip
#'  the curated information. Or use [as.data.frame()] to convert to another
#'  data format.
#'
#' @seealso [fcwt_batch()]
#'
#' @examples
#' ts_sin_440 <- sin((1:5000) * 2 * pi * 440 / 44100)
#'
#' fcwt(
#'   ts_sin_440,
#'   x_sample_freq = u(44.1, "kHz"),
#'   sigma = 5,
#'   freq_begin = u(50, "Hz"),
#'   freq_end = u(1000, "Hz"),
#'   n_freqs = 10
#' )
#' @export
fcwt <- function(x,
                 x_sample_freq,
                 sigma = 2 * pi,
                 y_sample_freq = 3 / sigma_res(sigma, freq_end)$time,
                 freq_begin = 2 * x_sample_freq / length(x),
                 freq_end = x_sample_freq / 2,
                 n_freqs =
                 # we want to assign one band per uncertainty interval
                 # so we have a similar frequency sampling than
                 # physical uncertainty.
                 # this calculation makes sense only for the log scale
                 # (since for the log scale the difference of neighboring
                 # axis values are proportional to the value itself and so is
                 # the uncertainty).
                 # we triple this number because we could get frequencies
                 # that lie just in the middle of two bands
                   3 * ceiling(
                     log(
                       du(freq_end / freq_begin),
                       base = 1 + sigma_freq_res_rel(sigma)
                     )
                   ),
                 freq_scale = c("log", "linear"),
                 phase = FALSE,
                 rm_coi = TRUE,
                 n_threads = 2L) {
  stopifnot(is.numeric(x))
  stopifnot(is.numeric(n_freqs), n_freqs > 0)
  stopifnot(is.numeric(sigma), sigma > 0)
  stopifnot(is.numeric(n_threads), n_threads >= 1)

  x_sample_freq <- as_freq(x_sample_freq)
  freq_begin <- as_freq(freq_begin)
  freq_end <- as_freq(freq_end)
  # this needs to be after freq_begin, freq_end
  y_sample_freq <- as_freq(y_sample_freq)
  stopifnot(x_sample_freq > u(0, "Hz"))
  stopifnot(
    y_sample_freq > u(0, "Hz"),
    y_sample_freq <= x_sample_freq
  )
  stopifnot(freq_begin > u(0, "Hz"))
  stopifnot(freq_end > freq_begin)

  freq_scale <- match.arg(freq_scale)
  stopifnot(isTRUE(phase) || isFALSE(phase))

  freq_scale_lgl <- (freq_scale == "linear")
  stopifnot(isTRUE(freq_scale_lgl) || isFALSE(freq_scale_lgl))

  w <- wnd_from_target_sample_freq(y_sample_freq, x_sample_freq)

  # only ratios of the frequencies enter the computation,
  # so any common unit works (we use Hz here)
  output <-
    fcwt_raw(
      as.numeric(x),
      hz(x_sample_freq),
      hz(freq_begin), hz(freq_end),
      as.integer(n_freqs), sigma,
      as.integer(w$size_n),
      as.integer(n_threads),
      freq_scale_lgl,
      phase
    )

  dim_t <- wnd_new_sc_dim(w, length(x))
  if (phase) {
    dim(output) <- c(dim_t, n_freqs, 3L)
    dimnames(output) <- list(NULL, NULL, sc_layer_names)
  } else {
    dim(output) <- c(dim_t, n_freqs)
  }

  # The window spans an integer number of samples, so the actual output
  # sample rate can deviate from the requested `y_sample_freq`.
  y_sample_freq_actual <- x_sample_freq / w$size_n

  if (rm_coi) {
    # Set the values inside the cone of influence to NA, column by column.
    # (This is done here, in place on the freshly created array: passing it
    # to a function that modifies it would create a full copy.)
    coi <- function(width) {
      coi_n_slices(
        dim_t, y_sample_freq_actual, freq_begin, freq_end, freq_scale, sigma,
        dim_f = n_freqs, width = width
      )
    }
    rows <- function(m) c(seq_len(m), seq.int(dim_t - m + 1, dim_t))

    n_coi <- coi(coi_width)
    for (j in seq_along(n_coi)) {
      m <- min(n_coi[[j]], dim_t)
      if (m > 0) {
        if (phase) {
          output[rows(m), j, c("modulus", "inst_freq")] <- NA_real_
        } else {
          output[rows(m), j] <- NA_real_
        }
      }
    }

    if (phase) {
      n_coi <- coi(coi_width_coherence)
      for (j in seq_along(n_coi)) {
        m <- min(n_coi[[j]], dim_t)
        if (m > 0) {
          output[rows(m), j, "coherence"] <- NA_real_
        }
      }
    }
  }

  fcwtr_scalogram(
    output,
    # time (offset) in the inverse unit of the sampling frequency
    time_offset = 0 / y_sample_freq_actual,
    y_sample_freq_actual, freq_begin, freq_end,
    freq_scale, sigma
  )
}
